"""Build assets/inf-sample.js for learn-llm-inference-with-phoebe from REAL public rows.

Source: RouteLLM's released dataset routellm/gpt4_dataset on Hugging Face (Apache-2.0, LICENSE file
read 2026-11-08), files train.jsonl (109,101 rows) and valid.jsonl (10,000 rows). Each row: a real
user prompt (lmsys-chat-1m, sharegpt, anthropic-hh, flan, ...), GPT-4's answer, Mixtral 8x7B's answer,
and `mixtral_score` 1-5: GPT-4 acting as judge, scoring Mixtral's answer.

What this script does (nothing else is invented):
 1. A cheap text-only router: 12 features of the prompt text (length, lines, code marks, digits,
    maths words, question marks, ...) and a logistic regression fit on train.jsonl to predict
    "Mixtral's answer scored 4 or 5". Seeded, sklearn defaults otherwise.
 2. 2,000 rows drawn from valid.jsonl (held out from the router fit) with seed 20261108.
 3. Per row it ships integers only: router score s (0-1000), judge score q (1-5), estimated tokens
    (characters / 4, rounded up) for the prompt, GPT-4's answer and Mixtral's answer, and a task id.
    No prompt or answer text is shipped.
 4. 3,000 exponential(1) gaps (seed 20261109), quantised to 1e-4, for the arrival queue.
Usage: python3 build-inf-sample.py <dir with train.jsonl valid.jsonl> <repo>
"""
import json, math, random, re, sys
import numpy as np
from sklearn.linear_model import LogisticRegression

SEED = 20261108
N_ROWS = 2000
CODE = re.compile(r"```|\bdef |\bfunction\b|\bclass |;\s*$|\{|\}|\bSELECT\b|#include|import ", re.M)
MATH = re.compile(r"\b(calculate|solve|equation|prove|integral|derivative|probability|how many|sum of|percent)\b", re.I)
CREATIVE = re.compile(r"\b(story|poem|essay|song|lyrics|creative|imagine|fiction|roleplay|role-play)\b", re.I)
REASON = re.compile(r"\b(explain|why|compare|analy[sz]e|step by step|reason)\b", re.I)

def feats(t):
    n = len(t)
    return [math.log1p(n), math.log1p(t.count("\n")), 1.0 if CODE.search(t) else 0.0,
            sum(c.isdigit() for c in t) / max(n, 1), 1.0 if MATH.search(t) else 0.0,
            1.0 if CREATIVE.search(t) else 0.0, 1.0 if REASON.search(t) else 0.0,
            min(t.count("?"), 5) / 5.0, sum(ord(c) > 127 for c in t) / max(n, 1),
            1.0 if re.search(r"\b(translate|summari[sz]e|rewrite|paraphrase)\b", t, re.I) else 0.0,
            1.0 if re.search(r"\b(list|bullet|table|json|format)\b", t, re.I) else 0.0,
            math.log1p(len(t.split()))]

def tok(s):
    return int(math.ceil(len(s or "") / 4.0))

def load(p):
    return [json.loads(l) for l in open(p, encoding="utf-8")]

def main(src, repo):
    tr = load(src + "/train.jsonl"); va = load(src + "/valid.jsonl")
    X = np.array([feats(r["prompt"]) for r in tr]); y = np.array([1 if r["mixtral_score"] >= 4 else 0 for r in tr])
    clf = LogisticRegression(max_iter=2000, random_state=SEED).fit(X, y)
    rng = random.Random(SEED)
    idx = sorted(rng.sample(range(len(va)), N_ROWS))
    tasks = sorted(set(r["source"][0] for r in va))
    rows = {"s": [], "q": [], "pin": [], "ob": [], "os": [], "task": []}
    pv = clf.predict_proba(np.array([feats(va[i]["prompt"]) for i in idx]))[:, 1]
    for k, i in enumerate(idx):
        r = va[i]
        rows["s"].append(int(round(float(pv[k]) * 1000)))
        rows["q"].append(int(r["mixtral_score"]))
        rows["pin"].append(tok(r["prompt"])); rows["ob"].append(tok(r["gpt4_response"])); rows["os"].append(tok(r["mixtral_response"]))
        rows["task"].append(tasks.index(r["source"][0]))
    g = random.Random(SEED + 1)
    gaps = [int(round(g.expovariate(1.0) * 10000)) for _ in range(3000)]
    # facts on the full splits, printed for the course map
    pall = clf.predict_proba(np.array([feats(r["prompt"]) for r in va]))[:, 1]
    yv = np.array([1 if r["mixtral_score"] >= 4 else 0 for r in va])
    order = np.argsort(-pall); ranks = np.empty(len(pall)); ranks[order] = np.arange(len(pall))
    pos = yv == 1; auc = (np.sum(len(pall) - ranks[pos]) - pos.sum() * (pos.sum() + 1) / 2) / (pos.sum() * (~pos).sum())
    facts = {"trainRows": len(tr), "validRows": len(va), "trainGoodShare": float(y.mean()), "validGoodShare": float(yv.mean()),
             "validAucRouter": float(auc), "coef": [round(float(c), 4) for c in clf.coef_[0]], "intercept": round(float(clf.intercept_[0]), 4)}
    data = {"source": "routellm/gpt4_dataset (Apache-2.0), valid.jsonl, 2,000 rows, seed 20261108",
            "tasks": tasks, "rows": rows, "gaps": gaps, "gapScale": 10000}
    with open(repo + "/assets/inf-sample.js", "w", encoding="utf-8") as f:
        f.write("/* inf-sample.js - generated by materials/build-inf-sample.py with json.dumps. Real rows: RouteLLM "
                "routellm/gpt4_dataset (Apache-2.0). Integers only, no prompt text. */\n")
        f.write("window.INF_SAMPLE = " + json.dumps(data, separators=(",", ":")) + ";\n")
    print(json.dumps(facts, indent=1))

if __name__ == "__main__":
    main(sys.argv[1], sys.argv[2])
